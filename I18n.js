function text(key, language) {
    var pair = messages[key] || messages.internal_error;
    return pair[language === "zh" ? 1 : 0];
}

function language(preference, locale) {
    return preference === "auto" ? (/^zh([_.-]|$)/i.test(locale) ? "zh" : "en") : preference;
}
